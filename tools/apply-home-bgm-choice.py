# coding: utf-8
"""Apply the explicit home choice without recomposing/re-encoding the approved file."""
from pathlib import Path
import hashlib, json, shutil, subprocess, sys, tempfile, warnings
import numpy as np
from scipy import signal
from scipy.io import wavfile

ROOT = Path(__file__).resolve().parent.parent
def apply_choice(track_id, choice):
    OUT = ROOT/choice.get('reportDirectory','reports/home-bgm-adoption-20261023')
    OUT.mkdir(parents=True, exist_ok=True)
    if choice['revision']=='first-demo-20261019':
        subprocess.run([sys.executable, str(ROOT/'tools/restore-first-home-bgm.py')], check=True, cwd=ROOT)
        return
    assert choice['playbackMode'] in ['full-track-loop','authored-intro-loop']
    source = ROOT/choice['source']
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    assert digest==choice['sha256'], 'The approved home master has changed'
    target = ROOT/'assets/audio'/(track_id+'.m4a')
    shutil.copy2(source, target)

    with tempfile.TemporaryDirectory() as temp:
        wav = Path(temp)/'read.wav'
        subprocess.run(['afconvert', '-f', 'WAVE', '-d', 'LEI16@44100', '-c', '2', str(target), str(wav)], check=True, capture_output=True)
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            sr, pcm = wavfile.read(wav)
        assert sr==44100
        x = pcm.astype(float)/32768
        duration = len(x)/sr
        loop_start = choice.get('loopStart',0)
        loop_end = choice.get('loopEnd',duration)
        assert 0<=loop_start<loop_end<=duration
        if choice['playbackMode']=='authored-intro-loop':
            assert loop_start>0 and loop_end<duration-.2
        rms = np.sqrt(np.mean(x*x))
        normalization = min(1., 10**(-23/20)/max(rms, 1e-12))
        # Keep the selected master's authored positions, including codec guards.
        # Analyze its harmony only for matching the existing soft reward cues.
        mono = signal.resample_poly(x.mean(axis=1), 1, 4)
        f, t, z = signal.stft(mono, sr/4, nperseg=4096, noverlap=3584, boundary=None)
        power = abs(z)**2
        good = (f>65)&(f<1500)
        pitch = np.rint(69+12*np.log2(np.maximum(f,1)/440)).astype(int)%12
        chroma = np.sqrt(np.array([power[good&(pitch==k)].sum(axis=0) for k in range(12)]))
        chroma /= np.maximum(np.linalg.norm(chroma, axis=0), 1e-12)
        beat = 60/choice['bpm']
        harmony = []
        for at in np.arange(0, duration-.1, 2*beat):
            v = chroma[:, (t>=max(0,at-.4))&(t<at+1.2)].mean(axis=1)
            candidates = []
            for root in range(12):
                for mode, third in [('major',4),('minor',3)]:
                    notes = [root,(root+third)%12,(root+7)%12]
                    candidates.append((float(v[notes].sum()+.12*v[root]),root,mode,notes))
            _, root, mode, notes = max(candidates, key=lambda row: row[0])
            fit = float(v[notes].sum()/max(v.sum(),1e-9))
            if fit<.43: root, mode = int(np.argmax(v)), 'open'
            harmony.append({'at':round(float(at),6),'root':root,'mode':mode,'fit':round(fit,3)})
        layout = {'loopStart':loop_start, 'loopEnd':loop_end, 'duration':duration,
                  'beatSeconds':beat, 'transitionCues':[round(float(at),6) for at in np.arange(0,duration,beat)],
                  'harmony':harmony, 'normalizationGain':float(normalization),
                  'sourceRevision':choice['revision'], 'sourceSha256':digest,
                  'playbackMode':choice['playbackMode']}
        if choice.get('editVerification'):layout['editVerification']=choice['editVerification']
        layouts_path = ROOT/'reports/adaptive-music-20261022/layouts.json'
        layouts_path.parent.mkdir(parents=True, exist_ok=True)
        layouts = json.loads(layouts_path.read_text()) if layouts_path.exists() else json.loads((ROOT/'src/audio/music-layouts.js').read_text().split('export const MUSIC_LAYOUTS = ',1)[1].strip().removesuffix(';'))
        layouts[track_id] = layout
        layouts_path.write_text(json.dumps(layouts, indent=2)+'\n')
        (ROOT/'src/audio/music-layouts.js').write_text('// Generated by tools/prepare-adaptive-music.py; explicit home choice by tools/apply-home-bgm-choice.py.\nexport const MUSIC_LAYOUTS = '+json.dumps(layouts,separators=(',',':'))+';\n')
        manifest_path = ROOT/'docs/selected-audio.json'
        manifest = json.loads(manifest_path.read_text())
        row = next((item for item in manifest if item['kind']=='bgm' and item['id']==track_id), None)
        if row is None:
            row = {'id':track_id, 'kind':'bgm', 'file':target.name}
            manifest.append(row)
        if choice.get('name'):row['name']=choice['name']
        if choice.get('storyPhase'):row.update(storyPhase=choice['storyPhase'], scene='ホーム・関連メニュー(フェーズ%d)'%choice['storyPhase'])
        for key in ['taskId','loopRefined','loopSourceStart','loopSourceEnd']:
            row.pop(key,None)
        row.update(duration=duration, bytes=target.stat().st_size, rms=float(20*np.log10(rms)),
                   introDuration=loop_start, loopStart=loop_start, loopEnd=loop_end, loopCrossfade=choice.get('loopCrossfade',0),
                   source=choice['source'], approvedFrom=choice['approvedFrom'], sourceRevision=choice['revision'],
                   sourceSha256=digest, normalizationGain=float(normalization), playbackMode=choice['playbackMode'])
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
        result = {'sourceRevision':choice['revision'], 'approvedFrom':choice['approvedFrom'],
                  'sourceSha256':digest, 'installedSha256':hashlib.sha256(target.read_bytes()).hexdigest(),
                  'byteIdenticalToSelectedMaster':source.read_bytes()==target.read_bytes(),
                  'duration':duration, 'loopStart':loop_start, 'loopEnd':loop_end, 'crossfadeSeconds':choice.get('loopCrossfade',0),
                  'normalizationGain':float(normalization), 'playbackRmsDb':float(20*np.log10(rms*normalization)),
                  'sampleJump':float(np.max(abs(x[round(loop_end*sr)-1]-x[round(loop_start*sr)])))}
        assert result['byteIdenticalToSelectedMaster'] and result['sampleJump']*normalization<.045
        (OUT/'verification.json').write_text(json.dumps(result, ensure_ascii=False, indent=2)+'\n')
        asset_path = ROOT/'reports/adaptive-music-20261022/asset-check.json'
        checks = [item for item in (json.loads(asset_path.read_text()) if asset_path.exists() else []) if item['id']!=track_id]
        checks.insert(0, {'id':track_id,'introSeconds':loop_start,'loopSeconds':loop_end-loop_start,
                         'loopJoinJump':result['sampleJump'],'peak':float(np.max(abs(x))),
                         'sourceRevision':choice['revision'],'normalizationGain':float(normalization)})
        asset_path.write_text(json.dumps(checks,indent=2)+'\n')
        wavfile.write(ROOT/'reports/adaptive-music-20261022'/(track_id+'-intro-preview.wav'),sr,pcm[:12*sr])
        start,end=round(loop_start*sr),round(loop_end*sr)
        wavfile.write(OUT/'full-track-repeat-preview.wav',sr,np.concatenate([pcm[end-6*sr:end],pcm[start:start+6*sr]]))
        print(json.dumps(result,ensure_ascii=False))


choices = json.loads((ROOT/'docs/audio-source-overrides.json').read_text())
for track_id in ['homeDefault', 'title', 'homePhase2', 'homePhase3']:
    if track_id in choices:apply_choice(track_id, choices[track_id])
