"""Restore the first home demo; loop its authored repetitions without a mix."""
from pathlib import Path
import hashlib, json, subprocess, tempfile, warnings
import numpy as np
from scipy.io import wavfile

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'reports/home-bgm-rollback-20261023'
OUT.mkdir(exist_ok=True)
SR = 44100

def read(file, wav):
    subprocess.run(['afconvert', '-f', 'WAVE', '-d', 'LEI16@44100', '-c', '2', str(file), str(wav)], check=True, capture_output=True)
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        rate, samples = wavfile.read(wav)
    assert rate == SR
    return samples.astype(float) / 32768

override = json.loads((ROOT / 'docs/audio-source-overrides.json').read_text())['title']
assert override['revision'] == 'first-demo-20261019'
source = ROOT / override['source']
target = ROOT / 'assets/audio/title.m4a'
beat = 60 / override['bpm']
start = round(override['introBars'] * override['beatsPerBar'] * beat * SR)
end = round(override['endBar'] * override['beatsPerBar'] * beat * SR)

with tempfile.TemporaryDirectory() as temp:
    temp = Path(temp)
    original = read(source, temp / 'source.wav')
    # A constant gain changes only loudness. Keep every original sample in order.
    gain = min(10**(-23 / 20) / np.sqrt(np.mean(original**2)), .79 / np.max(abs(original)))
    wavfile.write(temp / 'encoded.wav', SR, (original * gain * 32767).astype(np.int16))
    subprocess.run(['afconvert', '-f', 'm4af', '-d', 'aac', '-b', '96000', str(temp / 'encoded.wav'), str(target)], check=True, capture_output=True)
    final = read(target, temp / 'decoded.wav')
    # The composition repeats every four bars. Retain the first pass as intro;
    # wrap eight complete bars before the original demo's final fade begins.
    chords = [(2, 'minor'), (10, 'major'), (7, 'minor'), (9, 'major')]
    layout = {
        'loopStart': start / SR, 'loopEnd': end / SR,
        'duration': len(final) / SR, 'beatSeconds': beat,
        'transitionCues': [round(float(t), 6) for t in np.arange(0, end / SR, beat)],
        'harmony': [{'at': round(bar * 4 * beat, 6), 'root': chords[bar % 4][0], 'mode': chords[bar % 4][1]} for bar in range(12)],
        'sourceRevision': override['revision'],
    }
    layouts_path = ROOT / 'reports/adaptive-music-20261022/layouts.json'
    layouts = json.loads(layouts_path.read_text())
    layouts['title'] = layout
    layouts_path.write_text(json.dumps(layouts, indent=2) + '\n')
    (ROOT / 'src/audio/music-layouts.js').write_text('// Generated by tools/prepare-adaptive-music.py; home override by tools/restore-first-home-bgm.py.\nexport const MUSIC_LAYOUTS = ' + json.dumps(layouts, separators=(',', ':')) + ';\n')
    manifest_path = ROOT / 'docs/selected-audio.json'
    manifest = json.loads(manifest_path.read_text())
    row = next(x for x in manifest if x['kind'] == 'bgm' and x['id'] == 'title')
    for key in ['taskId', 'loopRefined', 'loopSourceStart', 'loopSourceEnd', 'loopCrossfade']:
        row.pop(key, None)
    row.update(duration=len(final)/SR, bytes=target.stat().st_size,
               rms=float(20*np.log10(np.sqrt(np.mean(final**2)))),
               introDuration=start/SR, loopStart=start/SR, loopEnd=end/SR,
               source=override['source'], sourceRevision=override['revision'], loopCrossfade=0)
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    # Compare the loop with the same chord transition inside the untouched demo.
    span = SR
    seam = np.concatenate([final[end-span:end], final[start:start+span]])
    reference = original[start-span:start+span] * gain
    error = float(np.sqrt(np.mean((seam-reference)**2)))
    signal = float(np.sqrt(np.mean(reference**2)))
    level = lambda x: float(20*np.log10(max(np.sqrt(np.mean(x*x)), 1e-12)))
    result = {
        'sourceRevision': override['revision'], 'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'fileSha256': hashlib.sha256(target.read_bytes()).hexdigest(),
        'duration': len(final)/SR, 'loopStart': start/SR, 'loopEnd': end/SR,
        'loopBars': override['endBar']-override['introBars'], 'crossfadeSeconds': 0,
        'constantGain': float(gain), 'loopReferenceErrorDb': float(20*np.log10(max(error/signal, 1e-12))),
        'sampleJump': float(np.max(abs(final[end-1]-final[start]))),
        'loopLevelDifferenceDb': abs(level(final[start:start+SR//2])-level(final[end-SR//2:end])),
    }
    (OUT/'verification.json').write_text(json.dumps(result, indent=2)+'\n')
    checks_path = ROOT/'reports/adaptive-music-20261022/asset-check.json'
    checks = json.loads(checks_path.read_text())
    checks = [entry for entry in checks if entry['id'] != 'title']
    checks.insert(0, {'id': 'title', 'introSeconds': start/SR, 'loopSeconds': (end-start)/SR,
                     'introJoinJump': float(np.max(abs(final[start]-final[start-1]))),
                     'loopJoinJump': result['sampleJump'], 'peak': float(np.max(abs(final))),
                     'sourceRevision': override['revision']})
    checks_path.write_text(json.dumps(checks, indent=2)+'\n')
    wavfile.write(ROOT/'reports/adaptive-music-20261022/title-intro-preview.wav', SR, (final[:start+6*SR]*32767).astype(np.int16))
    wavfile.write(OUT/'ホームBGM_最初の出力版.wav', SR, (final*32767).astype(np.int16))
    wavfile.write(OUT/'ホームBGM_折り返し確認.wav', SR, (np.concatenate([final[end-6*SR:end], final[start:start+6*SR]])*32767).astype(np.int16))
    assert result['loopReferenceErrorDb'] < -25, result
    assert result['sampleJump'] < .045, result
    print(json.dumps(result, ensure_ascii=False))
