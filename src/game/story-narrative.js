export function storyArc(axis) {
  return STORY_ARCS.find((a) => a.axis === axis) || null;
}
export function storyEpisode(axis, phase = 1) {
  return storyArc(axis)?.episodes[normalizePhase(phase)] || null;
}
export function episodeAccess(profile, axis, phase) {
  const p = normalizePhase(phase);
  if (!storyArc(axis)) return { available: false, cleared: false };
  return {
    available: p <= phaseOf(profile),
    cleared: normalizeStory(profile?.story)[p].includes(axis),
  };
}
/** 読了フラグを報酬に使わない。クリア済みの後日談だけ既存セーブから解放する。 */
export function storyPages(profile, axis, phase, part = "before") {
  const episode = storyEpisode(axis, phase);
  const access = episodeAccess(profile, axis, phase);
  if (!episode || !access.available || (part === "after" && !access.cleared))
    return [];
  return part === "after" ? episode.after : episode.before;
}
