// 公開情報で解く推理20問＋王を取って決着する10問。
import { L } from "../i18n/index.js";
const p = (owner, rank, at, king = false, label) => ({
  owner,
  rank,
  at,
  king,
  ...(label ? { label } : {}),
});
const obs = (from, to, extra = {}) => ({ from, to, ...extra });
const infer = (
  id,
  title,
  observation,
  question,
  options,
  correctOption,
  answer,
  hint,
  explanation,
  expectedCandidates,
  extra = {},
) => ({
  id,
  title,
  kind: "inference",
  level: id <= 5 ? L("初級") : id <= 11 ? L("中級") : L("応用"),
  size: 5,
  visibility: L("伏せ札の推理"),
  observation,
  pieces: [p(1, "?", observation.at(-1).to, false, "X")],
  question,
  options,
  correctOption,
  answer,
  hint,
  explanation,
  expectedCandidates,
  note: L("破線は観測した移動。図はXと経路のみ。各移動の間に入れ替え・王位継承はありません。"),
  ...extra,
});
const kingKnown = (rank) => ({ knownOtherKing: rank });
const unavailable = (rank) => ({
  excludedRanks: [rank],
  accountedCards: [{ rank, ownHand: 2, publicDiscard: 2 }],
});
const knownText = L("相手の王は別の8だと公開情報で確認できています。");
const captureInference = (
  id,
  title,
  rank,
  from,
  to,
  targets,
  size,
  explanation,
) =>
  infer(
    id,
    title,
    [obs(from, to, { targets, captured: targets })],
    L(
      "伏せ札Xが{from}から{to}へ1回で移動し、途中と着地点の{a}・{b}にいた自分の通常駒をまとめて取りました。Xの数字と王かどうかを答えてください。",
      { from, to, a: targets[0], b: targets[1] },
    ),
    [L("{rank}（王かは不明）", { rank }), L("王の{rank}", { rank }), L("JかQ"), "K"],
    1,
    L("王の{rank}です。", { rank }),
    L("進む方向・出発点からの距離の偶奇・途中の敵を取り続けた事実を合わせます。"),
    explanation,
    [rank + ":king"],
    {
      size,
      pieces: [
        p(1, "?", from, false, "X"),
        ...targets.map((at, i) => p(0, i ? "3" : "2", at)),
      ],
      note: L("図は移動前。破線の1回の移動で、示された自分の通常駒2枚が撃破されました。ほかの経路は空きマスです。"),
    },
  );
const finish = (
  id,
  title,
  actor,
  pieces,
  to,
  explanation,
  hint,
  size = 5,
  captureCount = 1,
  extra = {},
) => ({
  id,
  title,
  kind: "move",
  level: id <= 24 ? L("中級") : L("応用"),
  size,
  visibility: L("王を取って決着"),
  actor,
  pieces,
  captureCount,
  question: pieces.find((p) => p.at === actor).king
    ? L("{at}の王の{rank}を動かし、この一手で相手の王を取って勝ってください。", {
        at: actor,
        rank: pieces.find((p) => p.at === actor).rank,
      })
    : L("{at}の{rank}を動かし、この一手で相手の王を取って勝ってください。", {
        at: actor,
        rank: pieces.find((p) => p.at === actor).rank,
      }),
  solution: [{ from: actor, to }],
  answer: L("{from} → {to}。相手の王を取り、あなたの勝利。", { from: actor, to }),
  explanation,
  hint,
  note: L("あなたのターン。両軍の札を見せた練習用の途中局面です。図にある駒だけが残っています。"),
  ...extra,
});
